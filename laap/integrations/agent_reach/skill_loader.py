from laap.integrations.agent_reach import AgentReachBridge

_bridge = AgentReachBridge()


def skill_status(**kwargs) -> str:
    """Return a one-line status of Agent-Reach channels."""
    summary = _bridge.summary()
    if not summary.get("available"):
        return f"Agent-Reach unavailable: {summary.get('error', 'unknown')}"
    return (
        f"Agent-Reach v{summary.get('version', '?')}: "
        f"{summary['ok']}/{summary['total_channels']} channels active "
        f"({summary['warn']} warn, {summary['off']} off)"
    )


def skill_doctor(**kwargs) -> str:
    """Return the full Agent-Reach doctor report."""
    return _bridge.doctor_report()


def tool_reach_read(url: str = "", **kwargs) -> str:
    """Read any URL via Agent-Reach (Jina Reader)."""
    if not url:
        return "Error: url parameter required"
    return _bridge.read_url(url)


def tool_reach_search(query: str = "", **kwargs) -> str:
    """Semantic search via Agent-Reach (Exa + mcporter)."""
    if not query:
        return "Error: query parameter required"
    return _bridge.search(query)
