# ─────────────────────────────────
# 1. 代码所有权: 不是安装依赖, 是把源码拷贝进项目, 完全拥有
# 2. 无版本锁定: 你仓库里的就是 v1.0
# 3. Headless + 样式分离: Radix UI 管行为/无障碍, Tailwind 管视觉
# 4. CVA (class-variance-authority) 管理变体: size/intent/state
# 5. tailwind-merge 处理类名冲突

# 顶级组件必须具备的特质:
# ─────────────────────────
# - 行为: 键盘导航 + ARIA + 焦点管理 + 屏幕阅读器
# - 视觉: CSS 变量驱动 (不是硬编码), 暗色模式原生支持
# - 变体: CVA 类型安全, 调用方只需改 props
# - 性能: tree-shakeable, 只打包用到的

# ═══════════════════════════════════════════════════════════════
# 第二部分: 获奖设计的三位一体
# ═══════════════════════════════════════════════════════════════

# 一个 7 分和 9 分的差距永远在三个地方同时存在:
# ──────────────────────────────────────────────
# 1. 艺术指导 (Art Direction)
#    - 每一个排版、配色、网格为一个核心概念服务
#    - 去掉动效后, 静态帧仍然像有人精心设计过
#    - 不是"套模板", 是有观点的

# 2. 导演式动效 (Directed Motion)
#    - 不是"为了动画而动画"
#    - 转场有含义, 滚动有节奏, 微交互奖励注意力
#    - 动效有导演, 不只是有库

# 3. 性能 (Performance)
#    - 3D hero 在中端手机上不能掉到 18fps
#    - 9MB 页面 6 秒加载 = 不会获奖
#    - 美在 60fps = 完整的学科

# ═══════════════════════════════════════════════════════════════
# 第三部分: 技术栈决策指南
# ═══════════════════════════════════════════════════════════════

# 动画引擎选择
# ──────────────
# GSAP + ScrollTrigger: 所有需要序列化/滚动驱动的动画
#   - 不用 CSS animation 做复杂编排
#   - SplitText 做文字动画 (字符级/词语级/行级)
#   - gsap.matchMedia() 区分桌面/移动动画逻辑
# Three.js: 需要在 canvas 里做任何事
#   - 直接使用 Three.js (非 React Three Fiber)
#   - 当需要直接控制渲染循环 + 资源管理时
# Lenis: 平滑滚动, 通过 gsap.ticker 驱动与 GSAP 同步

# 组件库选择
# ──────────────
# shadcn/ui: 所有新项目的起点
# Radix UI: 需要 shadcn 没提供的基础组件时
# Lucide: 图标 (代替 emoji)
# Sonner: 通知/Toast

# ═══════════════════════════════════════════════════════════════
