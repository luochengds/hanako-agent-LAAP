# [避免] 四列 footer 网格

# 打破中心化的 8 个最高杠杆模式:
# ──────────────────────────────────
# 1. 非预期配色: 不用蓝紫, 用 土褐+墨绿 / 深蓝+赭石 / 冷灰+珊瑚
# 2. 不对称布局: 不用三等分, 用 5:3 / 黄金分割 / 之字形
# 3. 有意的留白: 不是"少放东西", 是"放对东西后剩下的空间"
# 4. 自定义光标: 跟随/磁吸/轨迹 — 微交互的第一接触点
# 5. 字号层级: 用 3-4 种字重/字号, 不用统一缩放
# 6. 网格打破: 偶尔让元素冲出网格边界 (叠层/溢出/负边距)
# 7. 材质感: 噪点纹理 / 细微颗粒 / 纸质感背景
# 8. 文字作为图形: 大字重标题 + 裁切/渐变/遮罩

# ═══════════════════════════════════════════════════════════════
# 第五部分: 实操清单 (生成前自检)
# ═══════════════════════════════════════════════════════════════

# 每次生成前端时自问:
# ─────────────────────
# [ ] 这个设计去除动画后还有灵魂吗? (艺术指导)
# [ ] 动画有含义还是只是为了动? (导演式动效)
# [ ] 我选了哪三个字体系列? 为什么是它们? (排版逻辑)
# [ ] 颜色在传达什么情绪? 不是"好看"而是"对" (色彩策略)
# [ ] 间距层级的逻辑是什么? 8/16/24/32/48? (间距系统)
# [ ] 交互反馈是什么? hover/active/focus 各是什么? (微交互)
# [ ] 暗色模式看起来是独立设计的还是自动转换的? (暗色模式)
# [ ] 在 4G 网络 + 中端手机上的加载体验如何? (性能)
# [ ] 去掉三个圆角 card + 紫蓝渐变 + Inter 后还剩什么? (反 AI 默认)

# 颜色选择优先级:
# ─────────────────
# 1. 单色系 (同一色相, 不同明度) — 最安全, 最优雅
# 2. 双色系 (主色 + 强调色, 色环距离 > 60度) — 最经典
# 3. 三色系 (主/辅/强调, 两个同色系 + 一个对比) — 高级
# 4. 避免: 紫蓝渐变 (2026年的 Comic Sans)

